"""Read-only preflight of a pinned physical customer database.

The caller is an authenticated, trusted backend. This verification is ONE
checkpoint, not a complete tenant-provisioning service or production approval.
It NEVER creates a database, issues a role, touches backups or activates a
customer. PostgreSQL custom settings are not authentication.
"""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from uuid import UUID
import re

from .accounting import AccountingError

_DB_ID = re.compile(r"^[a-z][a-z0-9_]{5,62}$")
_REQUIRED_TABLES = frozenset({
    "one_tenants", "one_memberships", "one_accounts", "one_journal_entries",
    "one_journal_lines", "one_invoice_docs", "one_payment_docs",
    "one_payment_allocations",
})


@dataclass(frozen=True, slots=True)
class DatabaseReadinessEvidence:
    """Checked facts, safe to retain only in trusted control-plane logging."""

    tenant_id: UUID
    database_name: str
    role_name: str
    observed_tables: tuple[str, ...]
    digest: bytes


def verify_physical_tenant_database(
    connection, *,
    expected_tenant: UUID,
    expected_actor: UUID,
    expected_database: str,
    expected_reader_role: str,
) -> DatabaseReadinessEvidence:
    """Require tenant-scoped READ ONLY access with pinned DB/role identity.

    Call from a vetted server-side connection factory with database and role
    names generated by the control plane, not supplied by the browser.
    Also independently verify pg_hba/database CONNECT policy and no other
    hidden tenant rows with a separate privileged infrastructure checker.
    """
    if (not isinstance(expected_tenant, UUID) or
            not isinstance(expected_actor, UUID) or
            not isinstance(expected_database, str) or
            not isinstance(expected_reader_role, str) or
            not _DB_ID.fullmatch(expected_database) or
            not _DB_ID.fullmatch(expected_reader_role)):
        raise AccountingError("Pinned tenant, reader role and database required")

    try:
        with connection.transaction():
            with connection.cursor() as cur:
                cur.execute(
                    "SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY"
                )
                cur.execute("SELECT current_database(),current_user")
                location = cur.fetchone()
                if location != (expected_database, expected_reader_role):
                    raise AccountingError("Unexpected database or reporting role")
                cur.execute(
                    """SELECT rolcanlogin,rolsuper,rolcreatedb,rolcreaterole,
                              rolreplication,rolbypassrls FROM pg_roles
                       WHERE rolname=current_user"""
                )
                grants = cur.fetchone()
                if grants != (True, False, False, False, False, False):
                    raise AccountingError("Database reporting role is privileged")
                cur.execute(
                    """SELECT has_database_privilege(current_user,
                               current_database(),'CREATE'),
                              has_schema_privilege(current_user,'public','CREATE'),
                              has_table_privilege(current_user,
                               'public.one_invoice_docs','SELECT'),
                              has_table_privilege(current_user,
                               'public.one_payment_docs','SELECT')"""
                )
                permissions = cur.fetchone()
                if permissions != (False, False, False, False):
                    raise AccountingError("Reporting role has excess grants")
                cur.execute(
                    """SELECT c.relname,c.relrowsecurity,c.relforcerowsecurity
                       FROM pg_class c JOIN pg_namespace n
                         ON n.oid=c.relnamespace
                       WHERE n.nspname='public'
                         AND c.relkind='r' AND c.relname = ANY(%s)""",
                    (sorted(_REQUIRED_TABLES),),
                )
                observed = cur.fetchall()
                by_name = {name: (bool(rls), bool(force))
                           for name, rls, force in observed}
                if (set(by_name) != _REQUIRED_TABLES or
                        any(value != (True, True)
                            for value in by_name.values())):
                    raise AccountingError("Missing ledger tables or forced RLS")

                # GUCs are RLS filters ONLY. The trusted backend has already
                # authenticated the actor; merely setting GUCs is not auth.
                cur.execute(
                    "SELECT set_config('one.tenant_id',%s,true)",
                    (str(expected_tenant),),
                )
                cur.execute(
                    "SELECT set_config('one.actor_id',%s,true)",
                    (str(expected_actor),),
                )
                cur.execute("SELECT id FROM one_tenants")
                tenants = cur.fetchall()
                if tenants != [(expected_tenant,)]:
                    raise AccountingError("Tenant identity does not match DB")
                cur.execute(
                    """SELECT role,active FROM one_memberships
                       WHERE tenant_id=%s AND actor_id=%s""",
                    (expected_tenant, expected_actor),
                )
                membership = cur.fetchone()
                if (membership is None or not membership[1] or
                        membership[0] not in
                        ("company_admin", "accountant", "viewer")):
                    raise AccountingError("No active tenant membership")
    except AccountingError:
        raise
    except Exception as error:
        # No internal SQL/credentials or provider details in the exception.
        raise AccountingError("Database readiness preflight unavailable") from error

    tables = tuple(sorted(_REQUIRED_TABLES))
    fingerprint = "|".join((
        "ONE_DATABASE_CHECK_V1", str(expected_tenant), expected_database,
        expected_reader_role, ",".join(tables),
    )).encode("utf-8")
    return DatabaseReadinessEvidence(
        tenant_id=expected_tenant, database_name=expected_database,
        role_name=expected_reader_role,
        observed_tables=tables, digest=sha256(fingerprint).digest(),
    )
